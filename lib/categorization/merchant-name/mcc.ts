/** Etichetta leggibile di un MCC (4 cifre), oppure `null` se mancante o sconosciuto. */
export function mccLabel(code: string | null | undefined): string | null {
  const normalized = code?.trim();
  if (!normalized || !/^\d{4}$/.test(normalized)) return null;
  return MCC_LABELS[normalized] ?? null;
}
